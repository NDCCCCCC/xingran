package client

import (
	"strings"
	"testing"
)

// 一个缩微的 swaggo docs.go 样本（含模板占位符与 $ref 定义）。
const sampleDocs = `// Package docs Code generated by swaggo/swag. DO NOT EDIT
package docs

import "github.com/swaggo/swag"

const docTemplate = ` + "`" + `{
    "swagger": "2.0",
    "info": {"title": "{{.Title}}", "version": "{{.Version}}"},
    "host": "{{.Host}}",
    "basePath": "{{.BasePath}}",
    "paths": {
        "/system/user/list": {
            "post": {
                "description": "分页获取用户列表",
                "summary": "获取用户列表",
                "tags": ["用户管理"],
                "parameters": [{
                    "description": "分页参数",
                    "name": "request",
                    "in": "body",
                    "required": true,
                    "schema": {"$ref": "#/definitions/request.PageParams"}
                }]
            }
        },
        "/system/user/{id}": {
            "post": {
                "description": "获取用户详情",
                "summary": "获取用户详情",
                "tags": ["用户管理"]
            }
        },
        "/ops/building/list": {
            "post": {"summary": "楼宇列表", "tags": ["楼宇管理"]}
        }
    },
    "definitions": {
        "request.PageParams": {
            "type": "object",
            "required": ["current"],
            "properties": {
                "current": {"type": "integer", "description": "页码，从1开始"},
                "pageSize": {"type": "integer", "description": "每页大小"}
            }
        }
    }
}` + "`" + `

var SwaggerTemplate = docTemplate
`

func TestParseSchema(t *testing.T) {
	eps, basePath, err := ParseSchema(sampleDocs)
	if err != nil {
		t.Fatalf("ParseSchema err: %v", err)
	}
	if len(eps) != 3 {
		t.Fatalf("endpoints = %d, want 3", len(eps))
	}
	// 排序后第一个是 /ops/building/list
	if eps[0].Path != "/ops/building/list" {
		t.Fatalf("first = %s", eps[0].Path)
	}

	// 找 user/list，验证 $ref 展开（样本 basePath 为模板占位符 → 视为空）
	var found *EndpointInfo
	for i := range eps {
		if eps[i].Path == "/system/user/list" {
			found = &eps[i]
		}
	}
	if found == nil {
		t.Fatalf("basePath=%q, eps=%+v", basePath, eps)
	}
	if found.Summary != "获取用户列表" || len(found.Tags) != 1 || found.Tags[0] != "用户管理" {
		t.Fatalf("found = %+v", found)
	}
	var hasCurrent bool
	for _, p := range found.Params {
		if p.Name == "current" {
			hasCurrent = true
			if !p.Required || p.Type != "integer" || p.Description != "页码，从1开始" {
				t.Fatalf("current param = %+v", p)
			}
		}
	}
	if !hasCurrent {
		t.Fatalf("未展开 $ref 字段: %+v", found.Params)
	}
}

func TestFilterEndpoints(t *testing.T) {
	eps, _, err := ParseSchema(sampleDocs)
	if err != nil {
		t.Fatalf("err: %v", err)
	}
	got := FilterEndpoints(eps, "/system/user")
	if len(got) != 2 {
		t.Fatalf("got = %d, want 2", len(got))
	}
	got = FilterEndpoints(eps, "system/user/list")
	if len(got) != 1 || got[0].Path != "/system/user/list" {
		t.Fatalf("got = %+v", got)
	}
	if len(FilterEndpoints(eps, "")) != 3 {
		t.Fatal("空 prefix 应返回全部")
	}
}

func TestParseSchemaWithBasePath(t *testing.T) {
	spec := strings.Replace(sampleDocs, `"basePath": "{{.BasePath}}"`, `"basePath": "/api/v1"`, 1)
	eps, _, err := ParseSchema(spec)
	if err != nil {
		t.Fatalf("err: %v", err)
	}
	found := false
	for _, e := range eps {
		if e.Path == "/api/v1/system/user/list" {
			found = true
		}
	}
	if !found {
		t.Fatalf("basePath 未拼接: %+v", eps)
	}
}

func TestParseSchemaMissingTemplate(t *testing.T) {
	if _, _, err := ParseSchema("package docs\nconst x = 1"); err == nil {
		t.Fatal("want error")
	} else if !strings.Contains(err.Error(), "docTemplate") {
		t.Fatalf("err = %v", err)
	}
}
